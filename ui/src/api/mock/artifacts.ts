export function visibleFeatures(s: ProjectState) {
  const ok = new Set(s.hypotheses.filter((h) => h.status === 'accepted').map((h) => h.id));
  return s.features.filter((f) => ok.has(f.hypothesisId));
}

export function listArtifacts(s: ProjectState): Artifact[] {
  return DEFS.filter((d) => d.exists(s)).map((d) => {
    const content = d.render(s);
    const v = s.artifactVersions[d.path] ?? { version: 1, updatedAt: s.project.createdAt };
    return {
      path: d.path,
      loop: d.loop,
      kind: d.kind,
      producedBy: d.producedBy,
      description: d.description,
      version: v.version,
      updatedAt: v.updatedAt,
      sizeBytes: new Blob([content]).size,
      content,
    };
  });
}
